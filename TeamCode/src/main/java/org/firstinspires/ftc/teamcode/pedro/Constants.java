public class Constants {

    static final double dtLength = 15.25;
    static final double dtWidth = 15.4375;
    public static MecanumConfig drivetrainConfig = new MecanumConfig(c -> {
        c.frontLeftName.set("leftFront");
        c.frontRightName.set("rightFront");
        c.backLeftName.set("leftBack");
        c.backRightName.set("rightBack");
        c.frontLeftDirection.set(DcMotorSimple.Direction.FORWARD);
        c.frontRightDirection.set(DcMotorSimple.Direction.REVERSE);
        c.backLeftDirection.set(DcMotorSimple.Direction.REVERSE);
        c.backRightDirection.set(DcMotorSimple.Direction.FORWARD);
    });

    public static SwerveConfig driveConfig = new SwerveConfig(
            c -> {
                c.zeroPowerBehavior.set(SwerveConfig.ZeroPowerBehavior.IGNORE_ANGLE_CHANGES);
                c.manualBrakeMode.set(true);
                c.voltageCompensation.set(false);
            }
    );
    public static CoaxialPodConfig rightBack = new CoaxialPodConfig(
            c -> {
                c.name.set("backRight");
                c.motorName.set("backRight");
                c.servoName.set("rbTurn");
                c.servoEncoderName.set("rbTurnEncoder");
                c.turnController.set(Controller.pid(0.3, 0, 0.005)
                        .plus(Controller.proportionalFeedforward(0)));
                c.driveDirection.set(DcMotorSimple.Direction.FORWARD);
                c.servoDirection.set(DcMotorSimple.Direction.FORWARD);
            }
    );
    public static CoaxialPodConfig leftFront = new CoaxialPodConfig(
            c -> {
                c.name.set("frontLeft");
                c.motorName.set("frontLeft");
                c.servoName.set("lfTurn");
                c.servoEncoderName.set("lfTurnEncoder");
                c.turnController.set(Controller.pid(0.3, 0, 0.005)
                        .plus(Controller.proportionalFeedforward(0)));
                c.driveDirection.set(DcMotorSimple.Direction.FORWARD);
                c.servoDirection.set(DcMotorSimple.Direction.FORWARD);
            }
    );
    public static CoaxialPodConfig rightFront = new CoaxialPodConfig(
            c -> {
                c.name.set("frontRight");
                c.motorName.set("frontRight");
                c.servoName.set("rfTurn");
                c.servoEncoderName.set("rfTurnEncoder");
                c.turnController.set(Controller.pid(0.3, 0, 0.005)
                        .plus(Controller.proportionalFeedforward(0)));
                c.driveDirection.set(DcMotorSimple.Direction.FORWARD);
                c.servoDirection.set(DcMotorSimple.Direction.FORWARD);
            }
    );
    public static CoaxialPodConfig leftBack = new CoaxialPodConfig(
            c -> {
                c.name.set("backLeft");
                c.motorName.set("backLeft");
                c.servoName.set("lbTurn");
                c.servoEncoderName.set("lbTurnEncoder");
                c.turnController.set(Controller.pid(0.3, 0, 0.0086)
                        .plus(Controller.proportionalFeedforward(0)));
                c.driveDirection.set(DcMotorSimple.Direction.FORWARD);
                c.servoDirection.set(DcMotorSimple.Direction.FORWARD);
            }
    );

    public static PinpointConfig localizerConfig = new PinpointConfig(c -> {
        c.name.set("pinpoint");
        c.podType.set(GoBildaPinpointDriver.GoBildaOdometryPods.goBILDA_SWINGARM_POD);
        c.xPodOffset.set(1.5335447957196573);
        c.yPodOffset.set(3.9759048702209956);
        c.xPodDirection.set(GoBildaPinpointDriver.EncoderDirection.FORWARD);
        c.yPodDirection.set(GoBildaPinpointDriver.EncoderDirection.FORWARD);
        c.globalDistanceUnit.set(DistanceUnit.INCH);
        c.offsetUnits.set(DistanceUnit.INCH);
    });

    public static ForesightConfig foresightConfig = new ForesightConfig(
            c -> {
                Controller primaryTranslationalForward = Controller.proportional(0.21667728319806506);
                Controller secondaryTranslationalForward = Controller.proportional(0.08005646641804712);
                Controller primaryTranslationalLateral = Controller.proportional(0.26672429552724874);
                Controller secondaryTranslationalLateral = Controller.proportional(0.098547500192882);

                c.forwardTranslational.set(Controller.piecewise(secondaryTranslationalForward).put(2.5, primaryTranslationalForward));
                c.strafeTranslational.set(Controller.piecewise(secondaryTranslationalLateral).put(2.5, primaryTranslationalLateral));

                c.coast.set(Controller.proportionalFeedforward(0.01248497409551979));
                c.brake.set(Controller.proportionalFeedforward(0.01061222798119182));

                c.headingFeedback.set(Controller.proportional(3.6783671048155178));
                c.headingBrakeCoefficients.set(Vector2D.cartesian(0.050617218528460114, 0.004457805085625844));

                c.linearBrakeCoefficients.set(Matrix.diag(0.0771987412801503, 0.04205627570660228));
                c.quadraticBrakeCoefficients.set(Matrix.diag(0.001084442834871161, 0.0018504010243842704));

                c.maxAchievableForwardVelocity.set(73.56136911022216);
                c.maxAchievableStrafeVelocity.set(62.92091528373446);
                c.naturalForwardDeceleration.set(37.528133791634815);
                c.naturalStrafeDeceleration.set(61.4238990969708);
            }
    );
    public static Follower create(HardwareMap h) {
        return new Follower(
                new PinpointLocalizer(h, localizerConfig),
                new Mecanum(h, drivetrainConfig),
                new Foresight(foresightConfig)
        );
    }
}